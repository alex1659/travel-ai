def generate_recommendations(destination, interests, days):
    destination = destination.lower().strip()

    # Universal dynamic fallback for unlisted locations
    if destination not in DESTINATION_DATA:
        generic_activities = [
            f"Explore famous local attractions, monuments, and viewpoints in {destination.title()}",
            f"Experience authentic street food markets and regional culinary specialties in {destination.title()}",
            f"Discover traditional art, culture, and historic heritage sites of {destination.title()}",
            f"Relax and take photos at scenic nature spots, riversides, and parks around {destination.title()}",
            f"Go shopping for local handicrafts, traditional textiles, and unique regional souvenirs",
            f"Visit popular spiritual, religious, or landmark sites in the area",
            f"Enjoy an evening leisure walk or local cultural gathering",
            f"Dine at top-rated regional restaurants and local cafes"
        ]
        
        itinerary = []
        gen_index = 0
        for day in range(1, days + 1):
            day_activities = []
            for time in ["09:00 AM", "12:00 PM", "03:00 PM", "06:00 PM"]:
                activity = generic_activities[gen_index % len(generic_activities)]
                day_activities.append({"time": time, "activity": activity})
                gen_index += 1
            itinerary.append({"day": day, "activities": day_activities})
        return itinerary

    destination_data = DESTINATION_DATA[destination]
    matched_activities = []

    # Collect activities based on user interests
    for interest in interests:
        interest = interest.lower().strip()
        if interest in destination_data:
            matched_activities.extend(destination_data[interest])

    # If no matching interests found, combine all available categories for that destination
    if not matched_activities:
        for category in destination_data:
            matched_activities.extend(destination_data[category])

    # Build unique daily schedules without repeating the exact same blocks consecutively
    itinerary = []
    activity_pool = list(matched_activities)
    
    for day in range(1, days + 1):
        day_activities = []
        times = ["09:00 AM", "12:00 PM", "03:00 PM", "06:00 PM"]
        
        for time in times:
            pool_index = ((day - 1) * len(times) + times.index(time)) % len(activity_pool)
            activity = activity_pool[pool_index]
            
            day_activities.append({
                "time": time,
                "activity": activity
            })

        itinerary.append({
            "day": day,
            "activities": day_activities
        })

    return itinerary